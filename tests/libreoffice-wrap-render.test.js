/**
 * LibreOffice Render Check — pictures and tables against their text
 *
 * The unit tests (picture-wrap, table-wrap) assert the XML; this asserts that
 * LibreOffice, which makes the PDFs and the template thumbnails, draws it as
 * Word does: a wrapped picture at the column's edge with the text beside it, a
 * picture behind the text at its spot on the page, and a table the text wraps
 * round. Needs soffice and gs; runs only with
 * RENDER_TESTS=1.
 *
 *   RENDER_TESTS=1 npx jest tests/libreoffice-wrap-render.test.js
 */

import { execFileSync } from 'child_process';
import fs from 'fs';
import os from 'os';
import path from 'path';
import zlib from 'zlib';

import HTMLtoDOCX from '../index.js';

const RENDER_TIMEOUT_MS = 180000;

const isAvailable = (command, args) => {
  try {
    execFileSync(command, args, { stdio: 'ignore', timeout: 60000 });
    return true;
  } catch (error) {
    return false;
  }
};

const renderRequested = process.env.RENDER_TESTS === '1';
const canRender =
  renderRequested && isAvailable('soffice', ['--version']) && isAvailable('gs', ['--version']);
const describeRender = canRender ? describe : describe.skip;

/** A solid square PNG, as a data URL. */
const solidPng = (size, [red, green, blue]) => {
  const crcTable = Array.from({ length: 256 }, (_, n) => {
    let c = n;
    for (let k = 0; k < 8; k += 1) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    return c >>> 0;
  });
  const crc = (buffer) => {
    let c = 0xffffffff;
    for (const byte of buffer) c = crcTable[(c ^ byte) & 0xff] ^ (c >>> 8);
    return (c ^ 0xffffffff) >>> 0;
  };
  const chunk = (type, data) => {
    const length = Buffer.alloc(4);
    length.writeUInt32BE(data.length);
    const body = Buffer.concat([Buffer.from(type, 'ascii'), data]);
    const sum = Buffer.alloc(4);
    sum.writeUInt32BE(crc(body));
    return Buffer.concat([length, body, sum]);
  };
  const header = Buffer.alloc(13);
  header.writeUInt32BE(size, 0);
  header.writeUInt32BE(size, 4);
  header.set([8, 2, 0, 0, 0], 8);
  const row = Buffer.concat([
    Buffer.from([0]),
    Buffer.from(Array(size).fill([red, green, blue]).flat()),
  ]);
  const pixels = zlib.deflateSync(Buffer.concat(Array(size).fill(row)));
  const png = Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk('IHDR', header),
    chunk('IDAT', pixels),
    chunk('IEND', Buffer.alloc(0)),
  ]);
  return `data:image/png;base64,${png.toString('base64')}`;
};

const parsePPM = (buffer) => {
  let offset = 0;
  // Its header's tokens, past whitespace and Ghostscript's "# Image
  // generated by" comment.
  const token = () => {
    for (;;) {
      const char = String.fromCharCode(buffer[offset]);
      if (char === '#') {
        while (buffer[offset] !== 0x0a) offset += 1;
      } else if (/\s/.test(char)) {
        offset += 1;
      } else {
        break;
      }
    }
    const start = offset;
    while (!/\s/.test(String.fromCharCode(buffer[offset]))) offset += 1;
    return buffer.toString('ascii', start, offset);
  };
  token();
  const width = Number(token());
  const height = Number(token());
  token();
  const pixels = buffer.slice(offset + 1);
  return {
    width,
    height,
    at(x, y) {
      const index = (Math.round(y) * width + Math.round(x)) * 3;
      return { red: pixels[index], green: pixels[index + 1], blue: pixels[index + 2] };
    },
  };
};

const isDark = ({ red, green, blue }) => red < 120 && green < 120 && blue < 120;

const TEXT = Array(14)
  .fill('The first week covers your accounts, data import and the templates your team uses most.')
  .join(' ');

describeRender('LibreOffice render: pictures and tables against their text', () => {
  let workDir;
  let page;

  beforeAll(async () => {
    workDir = fs.mkdtempSync(path.join(os.tmpdir(), 'htd-wrap-'));
    const red = solidPng(8, [255, 0, 0]);
    const blue = solidPng(8, [0, 0, 255]);
    const body =
      // A red picture wrapped left of a long paragraph, 12px from it.
      `<p><img src="${red}" width="100" height="100" data-wrap="left" data-wrap-gap="12">${TEXT}</p>` +
      // A blue picture behind the text, fixed on the page at 400, 700.
      `<p>Signed for Acme <img src="${blue}" width="80" height="40" data-wrap="behind" data-position="page" data-x="400" data-y="700"></p>` +
      // A green table wrapped on the right, the text beside it.
      `<table align="right" data-wrap="right" data-wrap-gap="12" data-no-spacing-after="true" style="width: 200px; table-layout: fixed"><tr><td style="background-color: #00FF00; height: 60px">Fee</td></tr></table>` +
      `<p>${TEXT}</p>`;
    const docxPath = path.join(workDir, 'wrap.docx');
    fs.writeFileSync(docxPath, await HTMLtoDOCX(body));
    execFileSync(
      'soffice',
      [
        '--headless',
        `-env:UserInstallation=file://${path.join(workDir, 'profile')}`,
        '--convert-to',
        'pdf',
        '--outdir',
        workDir,
        docxPath,
      ],
      { stdio: 'pipe', timeout: RENDER_TIMEOUT_MS }
    );
    const bitmapPath = path.join(workDir, 'page1.ppm');
    execFileSync(
      'gs',
      [
        '-q',
        '-dNOPAUSE',
        '-dBATCH',
        '-dSAFER',
        '-sDEVICE=ppmraw',
        '-r96',
        '-dFirstPage=1',
        '-dLastPage=1',
        `-sOutputFile=${bitmapPath}`,
        path.join(workDir, 'wrap.pdf'),
      ],
      { stdio: 'pipe', timeout: RENDER_TIMEOUT_MS }
    );
    page = parsePPM(fs.readFileSync(bitmapPath));
  }, RENDER_TIMEOUT_MS * 2);

  afterAll(() => {
    if (workDir) fs.rmSync(workDir, { recursive: true, force: true });
  });

  it('draws the wrapped picture at the column edge, the text beside it', () => {
    // The column starts 96px in (1" margins); the picture is 100px square.
    const inPicture = page.at(96 + 50, 96 + 50);
    expect(inPicture.red).toBeGreaterThan(200);
    expect(inPicture.green).toBeLessThan(80);
    // Text runs beside it: dark pixels right of picture + gap, level with it.
    let besideText = 0;
    for (let y = 96; y < 196; y += 2) {
      for (let x = 96 + 100 + 12; x < 96 + 400; x += 2) {
        if (isDark(page.at(x, y))) besideText += 1;
      }
    }
    expect(besideText).toBeGreaterThan(50);
  });

  it('draws the picture behind the text at its spot on the page', () => {
    const behind = page.at(400 + 40, 700 + 20);
    expect(behind.blue).toBeGreaterThan(180);
    expect(behind.red).toBeLessThan(120);
  });

  // A picture's transparency is not checked here: LibreOffice draws Word's Picture
  // Transparency (<a:alphaModFix>) solid, so the backend fades the picture's own pixels in the
  // copy it converts (RapidDocxBackend src/utils/pictureTransparency.ts).

  it('draws the wrapped table at the right margin', () => {
    let green = 0;
    for (let y = 96; y < page.height; y += 3) {
      const pixel = page.at(816 - 96 - 40, y);
      if (pixel.green > 200 && pixel.red < 80 && pixel.blue < 80) green += 1;
    }
    expect(green).toBeGreaterThan(5);
  });
});
